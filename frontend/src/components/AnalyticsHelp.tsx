export type AnalyticsHelpTopic = keyof typeof explanations;

export function AnalyticsSectionHeading({title, topic, onHelp}: {
  title: string; topic: AnalyticsHelpTopic; onHelp: (topic: AnalyticsHelpTopic) => void;
}) {
  return <div className="analytics-section-heading">
    <h2>{title}</h2>
    <button type="button" className="analytics-info-button" aria-label={`О разделе «${title}»`} aria-haspopup="dialog" onClick={() => onHelp(topic)}>
      <svg viewBox="0 0 24 24" fill="none" aria-hidden="true"><circle cx="12" cy="12" r="9" stroke="currentColor" strokeWidth="1.6" /><path d="M12 11v6" stroke="currentColor" strokeWidth="1.8" strokeLinecap="round" /><circle cx="12" cy="7.5" r="1" fill="currentColor" /></svg>
    </button>
  </div>;
}

export function AnalyticsHelpDialog({topic, onClose}: {topic: AnalyticsHelpTopic | null; onClose: () => void}) {
  const dialog = useRef<HTMLDialogElement>(null);
  const titleId = useId();
  useEffect(() => {
    if (!topic || !dialog.current) return;
    const element = dialog.current;
    const previousFocus = document.activeElement;
    const body = document.body;
    const overflow = body.style.overflow;
    const padding = body.style.paddingRight;
    const gutter = window.innerWidth - document.documentElement.clientWidth;
    // Сохраняем ширину страницы при блокировке фоновой прокрутки.
    if (gutter > 0) body.style.paddingRight = `${parseFloat(getComputedStyle(body).paddingRight) + gutter}px`;
    body.style.overflow = "hidden";
    element.showModal();
    return () => {
      element.close();
      body.style.overflow = overflow;
      body.style.paddingRight = padding;
      if (previousFocus instanceof HTMLElement && previousFocus.isConnected) previousFocus.focus({preventScroll: true});
    };
  }, [topic]);
  if (!topic) return null;
  const help = explanations[topic];
  return <dialog ref={dialog} className="analytics-help-dialog" aria-labelledby={titleId}
    onCancel={event => {event.preventDefault(); onClose();}}
    onClick={event => {
      if (event.target !== event.currentTarget) return;
      const box = event.currentTarget.getBoundingClientRect();
      if (event.clientX < box.left || event.clientX > box.right || event.clientY < box.top || event.clientY > box.bottom) onClose();
    }}>
    <header><h2 id={titleId}>{help.title}</h2><button type="button" className="analytics-dialog-close" aria-label="Закрыть пояснение" autoFocus onClick={onClose}><svg viewBox="0 0 24 24" fill="none" aria-hidden="true"><path d="m6 6 12 12M18 6 6 18" stroke="currentColor" strokeWidth="1.8" strokeLinecap="round" /></svg></button></header>
    <div className="analytics-help-body">{help.paragraphs.map(paragraph => <p key={paragraph}>{paragraph}</p>)}</div>
    <footer><button type="button" className="button primary" onClick={onClose}>Понятно</button></footer>
  </dialog>;
}
